import { GithubOwner, Stars } from '~/components/GithubOwner';
import { JsonLd } from '~/components/JsonLd';
import { Status } from '~/components/Status';
import { Waitlist } from '~/components/Waitlist';
import { ui } from '~/lib/copy';
import { asset, briefs, isMobileFirst, liveRunFor, manifest, runsFor, skills } from '~/lib/data';

/** The brief whose cells link to the skill's working live page instead of the static generation. */
const HOME_BRIEF = 'skillarena-home';
import { abs, meta } from '~/lib/seo';

const real = skills.filter((s) => !s.isBaseline);
const model = manifest.models.join(', ');
const description = `Compare ${real.length} UI skills for Claude Code and AI coding agents: same ${briefs.length} briefs, same model, ${manifest.runsPerPair} runs each. See the pages side by side before you install.`;

export const metadata = meta({ title: 'SkillArena — compare UI skills for AI coding agents', rawTitle: true, description, path: '/' });

const ld = [
    { '@type': 'WebSite', '@id': abs('/#website'), url: abs('/'), name: 'SkillArena', description, publisher: { '@id': abs('/#org') }, inLanguage: 'en' },
    {
        '@type': 'Dataset',
        '@id': abs('/#dataset'),
        name: 'SkillArena UI skill comparison',
        description: `${manifest.totals.calls} web pages generated by ${model} from ${briefs.length} fixed product briefs, once with no skill (control group) and once with each of ${real.length} UI skills, ${manifest.runsPerPair} runs per pair, with desktop and mobile screenshots.`,
        url: abs('/'),
        creator: { '@id': abs('/#org') },
        dateModified: manifest.lastGeneratedAt,
        isAccessibleForFree: true,
        keywords: ['UI skills', 'Claude Code skills', 'agent skills', 'SKILL.md', 'frontend design', 'AI generated UI', 'LLM evaluation'],
        measurementTechnique: 'Same brief and model for every condition; the skill is added to the system prompt; pages rendered in Chromium and screenshotted at 1440×900 and 390×844.',
        distribution: [{ '@type': 'DataDownload', encodingFormat: 'application/json', contentUrl: abs('/results.json') }],
    },
    {
        '@type': 'ItemList',
        name: 'UI skills compared on SkillArena',
        numberOfItems: real.length,
        itemListElement: real.map((s, i) => ({ '@type': 'ListItem', position: i + 1, name: s.name, url: abs(`/skill/${s.id}/`) })),
    },
];

export default function Home() {
    const firstReal = skills.find((s) => !s.isBaseline)?.id ?? 'baseline';
    return (
        <div className="wrap">
            <JsonLd items={ld} />
            <section className="hero">
                <h1>{ui['home.title']}</h1>
                <p className="hero-sub">
                    Same brief, same model, with and without the skill. {real.length} skills, {briefs.length} briefs, {manifest.totals.calls} pages, side by side.
                </p>
                <p className="lead2">{ui['home.lead']}</p>
                <p className="hero-cta">
                    <a className="btn btn-primary" href="#results">
                        See the results ↓
                    </a>{' '}
                    <a className="btn" href="/try/">
                        Try it with your own brief →
                    </a>
                </p>
                <p className="stats">
                    {manifest.totals.calls} {ui['home.stats']} ${manifest.totals.costUsd.toFixed(2)} · {manifest.models.join(', ')}
                </p>
            </section>

            <section className="results" id="results" aria-label="Results">
                <p className="muted small cell-note">{ui['home.cellNote']}</p>
                <p className="scroll-hint">{ui['home.scrollHint']}</p>
                <div className="matrix-scroll">
                    <table className="matrix">
                        <thead>
                            <tr>
                                <th scope="col">{ui['home.skill']}</th>
                                {briefs.map((b, i) => (
                                    <th key={b.id} scope="col" className={isMobileFirst(b.id) ? 'col-mobile' : undefined}>
                                        <a className="col-brief" href={`#brief-${b.id}`} title="Read this brief">
                                            <span className="num">{i + 1}</span>
                                            {b.title}
                                        </a>
                                    </th>
                                ))}
                            </tr>
                        </thead>
                        <tbody>
                            {skills.map((s, row) => (
                                <tr key={s.id} className={s.isBaseline ? 'baseline' : undefined}>
                                    <th scope="row">
                                        <a className="skill-name" href={`/skill/${s.id}/`}>
                                            {s.isBaseline ? 'No skill' : s.name}
                                        </a>
                                        {s.isBaseline ? (
                                            <div className="skill-meta">
                                                <span className="tag">control group</span>
                                            </div>
                                        ) : (
                                            <>
                                                <GithubOwner skill={s} />
                                                <div className="skill-meta">
                                                    <Stars skill={s} />
                                                    {s.featured && <span className="tag tag-featured">Featured</span>}
                                                    <a className="install-link" href={`/skill/${s.id}/#install`}>
                                                        <svg width="11" height="11" viewBox="0 0 16 16" aria-hidden="true" focusable="false">
                                                            <path fill="none" stroke="currentColor" strokeWidth="1.6" strokeLinecap="round" strokeLinejoin="round" d="M8 2v8m-3.5-3.5L8 10l3.5-3.5M3 13.5h10" />
                                                        </svg>
                                                        Install
                                                    </a>
                                                </div>
                                            </>
                                        )}
                                    </th>
                                    {briefs.map((b) => {
                                        const first = runsFor(b.id, s.id)[0];
                                        const mobile = isMobileFirst(b.id);
                                        const alt = `${s.isBaseline ? 'Baseline' : s.name} — ${b.title}`;
                                        return (
                                            <td key={b.id} className={mobile ? 'col-mobile' : undefined}>
                                                {first?.hasShots ? (
                                                    <div className={mobile ? 'thumb-wrap mobile' : 'thumb-wrap'}>
                                                    <a className={mobile ? 'cell mobile' : 'cell'} href={`/skill/${s.id}/#${b.id}`} aria-label={alt}>
                                                        <img
                                                            src={asset(first, mobile ? 'thumb-mobile.webp' : 'thumb-desktop.webp')}
                                                            alt={alt}
                                                            width={mobile ? 300 : 600}
                                                            height={mobile ? 650 : 375}
                                                            loading={row < 2 ? 'eager' : 'lazy'}
                                                            decoding="async"
                                                            fetchPriority={row === 0 ? 'high' : undefined}
                                                        />
                                                    </a>
                                                    {b.id === HOME_BRIEF && liveRunFor(s.id) ? (
                                                        // "SkillArena itself": the working live page this skill built (/live/), in a new tab.
                                                        <a className="thumb-live" href={`${liveRunFor(s.id)!.base}index.html?ref=matrix`} target="_blank" rel="noopener">
                                                            {ui['action.open']} ↗
                                                        </a>
                                                    ) : (
                                                        <button
                                                            type="button"
                                                            className="thumb-live"
                                                            data-live-src={asset(first, 'index.html')}
                                                            data-live-title={`${s.isBaseline ? 'No skill' : s.name} · ${b.title} · run ${first.run}`}
                                                            data-live-view={mobile ? 'mobile' : 'desktop'}
                                                        >
                                                            {ui['action.open']}
                                                        </button>
                                                    )}
                                                    </div>
                                                ) : (
                                                    <a href={`/skill/${s.id}/#${b.id}`} style={{ textDecoration: 'none' }}>
                                                        <Status run={first} compact />
                                                    </a>
                                                )}
                                            </td>
                                        );
                                    })}
                                </tr>
                            ))}
                        </tbody>
                    </table>
                </div>
            </section>

            <section className="briefs" id="briefs" aria-labelledby="briefs-title">
                <h2 id="briefs-title">{ui['home.briefsTitle']}</h2>
                <p className="muted small">{ui['home.briefsLead']}</p>
                <ol className="brief-cards">
                    {briefs.map((b, i) => (
                        <li key={b.id} className="brief-card" id={`brief-${b.id}`}>
                            <h3>
                                <span className="num">{i + 1}</span>
                                {b.title}
                            </h3>
                            <blockquote>{b.text}</blockquote>
                            <a href={`/compare/?a=baseline&b=${firstReal}&brief=${b.id}`}>{ui['home.briefCompare']}</a>
                        </li>
                    ))}
                </ol>
                <p className="small muted" style={{ marginTop: 12 }}>
                    Have a product of your own? <a href="/try/">Compare skills on your brief →</a>
                </p>
            </section>

            <Waitlist />
        </div>
    );
}
